"""M08 candidate ranking and recommendation contracts.

The module is deliberately deterministic: recommendation text is assembled from
the structured score dimensions and never generated by an LLM.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum
from typing import Any


class RecommendationCategory(StrEnum):
    PREFERRED = "preferred"
    ALTERNATIVE = "alternative"
    NEEDS_REVIEW = "needs_review"
    INELIGIBLE = "ineligible"


class RankingStatus(StrEnum):
    RECOMMENDATIONS = "recommendations"
    NO_RECOMMENDATION = "no_recommendation"


@dataclass(frozen=True)
class ScoreDimension:
    name: str
    score: float
    weight: float
    reason: str
    fact_ids: list[str] = field(default_factory=list)
    evidence_ids: list[str] = field(default_factory=list)
    missing_reason: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {"name": self.name, "score": self.score, "weight": self.weight,
                "reason": self.reason, "fact_ids": list(self.fact_ids),
                "evidence_ids": list(self.evidence_ids), "missing_reason": self.missing_reason}


@dataclass(frozen=True)
class CandidateScore:
    """Aggregate score for one candidate, retained as a stable public contract."""
    candidate_id: str
    total_score: float
    dimensions: list[ScoreDimension] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {"candidate_id": self.candidate_id, "total_score": self.total_score,
                "dimensions": [x.to_dict() for x in self.dimensions]}


@dataclass(frozen=True)
class RecommendationReason:
    text: str
    kind: str = "positive"
    fact_ids: list[str] = field(default_factory=list)
    evidence_ids: list[str] = field(default_factory=list)
    missing_reason: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {"text": self.text, "kind": self.kind, "fact_ids": list(self.fact_ids),
                "evidence_ids": list(self.evidence_ids), "missing_reason": self.missing_reason}


@dataclass(frozen=True)
class Recommendation:
    candidate_id: str
    category: RecommendationCategory
    rank: int | None
    total_score: float | None
    dimensions: list[ScoreDimension] = field(default_factory=list)
    reasons: list[RecommendationReason] = field(default_factory=list)
    risks: list[RecommendationReason] = field(default_factory=list)
    gaps: list[RecommendationReason] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {"candidate_id": self.candidate_id, "category": self.category.value,
                "rank": self.rank, "total_score": self.total_score,
                "dimensions": [x.to_dict() for x in self.dimensions],
                "reasons": [x.to_dict() for x in self.reasons],
                "risks": [x.to_dict() for x in self.risks],
                "gaps": [x.to_dict() for x in self.gaps]}


@dataclass(frozen=True)
class RankingResult:
    status: RankingStatus
    preferred: Recommendation | None
    alternatives: list[Recommendation] = field(default_factory=list)
    needs_review: list[Recommendation] = field(default_factory=list)
    ineligible: list[Recommendation] = field(default_factory=list)
    rule_version: str = "m08-v1"

    @property
    def recommendations(self) -> list[Recommendation]:
        return ([self.preferred] if self.preferred else []) + list(self.alternatives)

    def to_dict(self) -> dict[str, Any]:
        return {"status": self.status.value, "preferred": self.preferred.to_dict() if self.preferred else None,
                "alternatives": [x.to_dict() for x in self.alternatives],
                "needs_review": [x.to_dict() for x in self.needs_review],
                "ineligible": [x.to_dict() for x in self.ineligible],
                "rule_version": self.rule_version}


__all__ = ["RecommendationCategory", "RankingStatus", "ScoreDimension", "CandidateScore",
           "RecommendationReason", "Recommendation", "RankingResult"]
